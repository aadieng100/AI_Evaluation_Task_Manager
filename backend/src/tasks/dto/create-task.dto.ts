import { IsInt, IsNotEmpty, IsOptional, IsString, IsUUID, Max, Min } from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class CreateTaskDto {
  @ApiProperty({ example: 'Evaluate Python Backtracking Logic', description: 'Title of the AI evaluation task' })
  @IsString()
  @IsNotEmpty()
  title: string;

  @ApiProperty({ example: 'Write a function to solve N-Queens in Python.', description: 'Prompt sent to AI models' })
  @IsString()
  @IsNotEmpty()
  prompt: string;

  @ApiProperty({ example: 'def solveNQueens(n): ...', description: 'Response generated by Model A' })
  @IsString()
  @IsNotEmpty()
  modelA: string;

  @ApiProperty({ example: 'class Solution: def solveNQueens(self, n): ...', description: 'Response generated by Model B' })
  @IsString()
  @IsNotEmpty()
  modelB: string;

  @ApiPropertyOptional({ example: 'Claude 3.5 Sonnet', default: 'Model A' })
  @IsString()
  @IsOptional()
  modelAName?: string;

  @ApiPropertyOptional({ example: 'GPT-4o', default: 'Model B' })
  @IsString()
  @IsOptional()
  modelBName?: string;

  @ApiPropertyOptional({ example: 1, description: 'Task priority (1: Low, 5: Critical)', default: 1 })
  @IsInt()
  @Min(1)
  @Max(5)
  @IsOptional()
  priority?: number;

  @ApiPropertyOptional({ example: 'usr_uuid_123', description: 'User ID of assigned evaluator' })
  @IsUUID()
  @IsOptional()
  assigneeId?: string;
}
